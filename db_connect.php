<?php
    // กำหนดรายละเอียดการเชื่อมต่อฐานข้อมูล
    // ***สำคัญมาก***: คุณต้องเปลี่ยนค่าเหล่านี้ให้ตรงกับข้อมูลของเซิร์ฟเวอร์ MySQL ของคุณ
    // จากข้อผิดพลาดที่คุณได้รับ, Host คือ '10.106.208.46', Database Name คือ 'chutikarnceramic' และ Username คือ 'root'
    $host = '10.106.208.46'; // เปลี่ยนจาก IP address เป็น 'localhost' เพื่อเชื่อมต่อกับเครื่องตัวเอง
    $port = '3306'; // พอร์ต MySQL (ค่าเริ่มต้นส่วนใหญ่คือ 3306)
    $dbname = 'chutikarnceramic1'; // ชื่อฐานข้อมูลของคุณ
    $username = 'root';  // ชื่อผู้ใช้สำหรับเข้าถึงฐานข้อมูล (ควรหลีกเลี่ยงการใช้ 'root' ใน Production)
    $password = '12345678'; // รหัสผ่านสำหรับชื่อผู้ใช้ที่ระบุ (ตรวจสอบว่าถูกต้อง)

    // สร้างการเชื่อมต่อกับฐานข้อมูล
    // ใช้ @ เพื่อระงับการแสดงผลข้อผิดพลาดเริ่มต้นของ PHP ชั่วคราว เพื่อให้เราจัดการเองได้
    $conn = new mysqli("10.106.208.46", "root", "12345678", "chutikarnceramic", 3306);

    // ตรวจสอบว่าการเชื่อมต่อสำเร็จหรือไม่
    if ($conn->connect_error) {
        // ถ้าการเชื่อมต่อล้มเหลว, ให้แสดงข้อความผิดพลาดที่ละเอียดขึ้นและหยุดการทำงานของสคริปต์
        die("การเชื่อมต่อฐานข้อมูลล้มเหลว: " . $conn->connect_error . "<br>โปรดตรวจสอบข้อมูลต่อไปนี้:" .
            "<br>- Host: " . $host .
            "<br>- Port: " . $port .
            "<br>- Database Name: " . $dbname .
            "<br>- Username: " . $username .
            "<br>- Password: (ตรวจสอบว่าถูกต้อง)" .
            "<br>และตรวจสอบว่าผู้ใช้ฐานข้อมูลมีสิทธิ์เข้าถึงฐานข้อมูลนี้");
    }

    // หากเชื่อมต่อสำเร็จ
    echo "เชื่อมต่อฐานข้อมูลสำเร็จ!";

    // ***สำคัญ***: ปิดการเชื่อมต่อฐานข้อมูลเมื่อใช้งานเสร็จสิ้น เพื่อประหยัดทรัพยากร
    $conn->close();

?>
